const MAP = new Map<string, string>();
const key = (s: string) => s.normalize('NFC').replace(/\u200D/g, ''); // ASR output often drops the ZWJ in ්‍ර
for (const [en, variants] of LIST) for (const v of variants) MAP.set(key(v), en);

const PUNCT = /^([("'“‘]*)(.*?)([)"'”’.,!?:;।]*)$/su;

/** English spelling for a Sinhala-script word, keeping surrounding punctuation; null when not in the list. */
export function englishFor(word: string): string | null {
  const m = PUNCT.exec(word);
  if (!m) return null;
  const en = MAP.get(key(m[2]));
  return en ? m[1] + en + m[3] : null;
}
